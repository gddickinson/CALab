"""FastAPI web app for CALab: serves the front end in static/ and the JSON API under /api.

Run with `python run_web.py` (http://127.0.0.1:8103, local only). `scripts/build_static.py` exports every path in
STATIC_ENDPOINTS to JSON for the GitHub Pages site, so keep that list in step with the GET routes below.
POST /api/run (the real Python plugins stepping a grid) is server-only; the static site steps in JS instead.
"""
from pathlib import Path

from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

from web import catalogue as cat

STATIC = Path(__file__).resolve().parent / "static"

app = FastAPI(title="CALab")
app.mount("/static", StaticFiles(directory=STATIC), name="static")


@app.get("/", include_in_schema=False)
def index():
    return FileResponse(STATIC / "index.html")


@app.get("/api/info")
def info():
    """Project summary and counts for the home page."""
    rules = cat.catalogue()
    return {
        "title": "CALab", "subtitle": "Cellular Automata Laboratory",
        "automata": len(rules), "patterns": sum(len(r["patterns"]) for r in rules),
        "categories": len(cat.PLUGIN_CATEGORIES), "max_states": max(r["num_states"] for r in rules),
    }


@app.get("/api/rules")
def rules():
    """The rule catalogue: metadata, docs, colour maps, parameters and preset names from the plugin registry."""
    return cat.catalogue()


@app.get("/api/patterns/{key}")
def patterns(key: str):
    """Every preset of one automaton, generated by its plugin, as encoded grids."""
    if key not in cat.PLUGIN_REGISTRY:
        raise HTTPException(404, f"unknown automaton {key}")
    return cat.patterns(key)


class RunRequest(BaseModel):
    rule: str
    width: int = Field(gt=0, le=400)
    height: int = Field(gt=0, le=400)
    cells: str
    steps: int = Field(ge=0, le=5000)
    params: dict = {}
    row: int = 0


@app.post("/api/run")
def run(req: RunRequest):
    """Step a grid N times with the real Python engine (used to cross-check the browser engine)."""
    try:
        return cat.run(req.rule, req.cells, req.width, req.height, req.steps, req.params, req.row)
    except KeyError:
        raise HTTPException(404, f"unknown automaton {req.rule}") from None
    except ValueError as e:
        raise HTTPException(400, str(e)) from None


# GET paths (without the /api prefix) written to the static site as api/<path>.json.
STATIC_ENDPOINTS = ["/info", "/rules"] + [f"/patterns/{k}" for k in cat.PLUGIN_REGISTRY]
