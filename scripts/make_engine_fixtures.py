"""Generate tests/fixtures/ca_engine_fixtures.json: start grids and the grids the real Python plugins reach after N steps.

The node test web/static/ca_engine.test.mjs asserts the JS engine reproduces every case cell for cell, and
tests/test_web.py re-runs every case through POST /api/run to check the fixtures still match the Python code.
Every start grid is built by the repo's own code: each plugin preset (create_automaton, numpy seeded), plus a
seeded random soup over all of the automaton's states, plus parameter variants (Wolfram rule, cyclic N/T).

Run: python scripts/make_engine_fixtures.py
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from web import catalogue as cat  # noqa: E402
from web.grid_codec import encode  # noqa: E402

OUT = ROOT / "tests" / "fixtures" / "ca_engine_fixtures.json"
SIZE, STEPS = 40, 20            # presets
SOUP, SOUP_STEPS = 24, 12       # random soups over every state


def case(key, label, grid, steps, params=None, row=0):
    h, w = grid.shape
    res = cat.run(key, encode(grid), w, h, steps, params or {}, row)
    return {"rule": key, "label": label, "width": w, "height": h, "steps": steps, "params": params or {},
            "row": row, "start": encode(grid), "end": res["cells"], "end_row": res["row"],
            "generation": res["generation"]}


def soup(states, w, h, seed):
    return np.random.default_rng(seed).integers(0, states, size=(h, w)).astype(np.int32)


def build():
    cases = []
    for i, entry in enumerate(cat.catalogue()):
        key = entry["key"]
        for p in entry["patterns"]:
            a = cat.make_pattern(key, p["name"], SIZE, SIZE, p["parameters"])
            params = {k: v for k, v in p["parameters"].items() if k in ("num_states", "threshold")}
            cases.append(case(key, f"preset {p['name']}", a.grid.copy(), STEPS, params,
                              int(getattr(a, "current_row", 0))))
        states = 2 if key in cat.ELEMENTARY else entry["num_states"]
        cases.append(case(key, "random soup", soup(states, SOUP, SOUP, 100 + i), SOUP_STEPS))
    # parameter variants
    for rule in (184, 73, 45):
        g = np.zeros((10, 16), dtype=np.int32)
        g[0] = soup(2, 16, 1, rule)[0]
        cases.append(case("rule_30", f"rule {rule}, runs past the last row", g, 15, {"rule": rule}))
    g = soup(2, 20, 12, 7)
    cases.append(case("rule_110", "start mid-grid (row 4)", g, 5, {"rule": 110}, row=4))
    for n, t in ((8, 1), (20, 4), (3, 2)):
        cases.append(case("cyclic_ca", f"N={n} T={t} soup", soup(n, SOUP, SOUP, n * 10 + t), SOUP_STEPS,
                          {"num_states": n, "threshold": t}))
    return cases


if __name__ == "__main__":
    cases = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"note": "generated by scripts/make_engine_fixtures.py; do not edit", "cases": cases},
                              separators=(",", ":")))
    print(f"{len(cases)} cases -> {OUT} ({OUT.stat().st_size / 1e3:.0f} kB)")
